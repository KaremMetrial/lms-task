/**
 * Builds a student on a monthly plan for January 2026, engaged with $count
 * instructors, each watching $seconds.
 *
 * @param  list<int>  $seconds  watch time per instructor, in order
 * @return array{0: Subscription, 1: list<Instructor>}
 */
function scenario(int $instructors = 3, array $seconds = [], string $period = '2026-01'): array
{
    $student = Student::factory()->create();

    $subscription = Subscription::factory()
        ->for($student)
        ->plan(Plan::Monthly)
        ->startingOn('2026-01-01')
        ->create();

    Payment::factory()->forSubscription($subscription)->create();

    $created = [];

    for ($i = 0; $i < $instructors; $i++) {
        $instructor = Instructor::factory()->create();
        $course = Course::factory()->for($instructor)->create();

        Engagement::factory()
            ->for($student)
            ->forCourse($course)
            ->inPeriod($period)
            ->watched($seconds[$i] ?? 3_600)
            ->create();

        $created[] = $instructor;
    }

    return [$subscription, $created];
}

function allocate(Subscription $subscription, string $period = '2026-01'): AllocationResult
{
    return app(AllocateSubscriptionPeriod::class)->execute($subscription, $period);
}

// ─────────────────────────────────────────────────────────────────────────────
// The happy path, end to end
// ─────────────────────────────────────────────────────────────────────────────

it('recognises a full month, takes the platform cut and splits the rest', function () {
    [$subscription, $instructors] = scenario(instructors: 3);

    $result = allocate($subscription);

    expect($result->outcome)->toBe(AllocationOutcome::Allocated);

    $allocation = $result->allocation->fresh('lines');

    // 299.00 EGP for all of January, 30% platform cut.
    expect($allocation->gross_minor->minor)->toBe(29_900)
        ->and($allocation->platform_minor->minor)->toBe(8_970)
        ->and($allocation->instructor_pool_minor->minor)->toBe(20_930)
        ->and($allocation->days_in_period)->toBe(31)
        ->and($allocation->strategy)->toBe('equal_weight');

    // The worked example: 20_930 ÷ 3 → two instructors get the extra piastre.
    $amounts = $allocation->lines->sortBy('instructor_id')
        ->pluck('amount_minor')->map(fn ($m) => $m->minor)->values()->all();

    expect($amounts)->toBe([6_977, 6_977, 6_976])
        ->and(array_sum($amounts))->toBe(20_930);
});

it('keeps gross exactly equal to platform plus instructor lines', function () {
    [$subscription] = scenario(instructors: 3);

    $allocation = allocate($subscription)->allocation->fresh('lines');

    expect($allocation->balances())->toBeTrue();
});

it('writes one earning ledger entry per non-zero line and moves the balance', function () {
    [$subscription, $instructors] = scenario(instructors: 3);

    allocate($subscription);

    expect(LedgerEntry::count())->toBe(3);

    foreach ($instructors as $instructor) {
        $entry = LedgerEntry::where('instructor_id', $instructor->id)->sole();

        expect($entry->type->value)->toBe('earning')
            ->and($entry->source_type)->toBe('allocation_line')
            ->and($entry->amount_minor->minor)->toBeIn([6_976, 6_977])
            // Business time, not wall clock: January earnings occurred in January.
            ->and($entry->occurred_at->format('Y-m'))->toBe('2026-01');

        $balance = InstructorBalance::find($instructor->id);

        expect($balance->earned_minor->minor)->toBe($entry->amount_minor->minor)
            ->and($balance->paid_minor->isZero())->toBeTrue()
            ->and($balance->reserved_minor->isZero())->toBeTrue()
            // Generated by MySQL from the other three columns.
            ->and($balance->available_minor->minor)->toBe($entry->amount_minor->minor);
    }
});

