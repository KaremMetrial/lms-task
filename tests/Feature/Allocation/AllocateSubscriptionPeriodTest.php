it('running allocation twice does not pay twice', function () {
    [$subscription, $instructors] = scenario(instructors: 3);

    $first = allocate($subscription);
    $second = allocate($subscription);

    expect($first->outcome)->toBe(AllocationOutcome::Allocated)
        // Reported distinctly, so a replay is never mistaken for real work.
        ->and($second->outcome)->toBe(AllocationOutcome::AlreadyAllocated)
        ->and($second->allocation->id)->toBe($first->allocation->id);

    // Nothing duplicated at any layer.
    expect(Allocation::count())->toBe(1)
        ->and(AllocationLine::count())->toBe(3)
        ->and(LedgerEntry::count())->toBe(3);

    // And critically: balances did not move a second time.
    foreach ($instructors as $instructor) {
        expect(InstructorBalance::find($instructor->id)->earned_minor->minor)
            ->toBeIn([6_976, 6_977]);
    }
});

it('running allocation ten times leaves balances untouched after the first', function () {
    [$subscription, $instructors] = scenario(instructors: 3);

    allocate($subscription);

    // Compare minor units, not Money instances: two Money objects with the same
    // value are equal but not identical, and toBe() checks identity.
    $earnedSnapshot = fn (): array => InstructorBalance::orderBy('instructor_id')
        ->get()
        ->mapWithKeys(fn ($b) => [$b->instructor_id => $b->earned_minor->minor])
        ->all();

    $versionSnapshot = fn (): array => InstructorBalance::orderBy('instructor_id')
        ->pluck('version', 'instructor_id')->all();

    $earnedBefore = $earnedSnapshot();
    $versionsBefore = $versionSnapshot();

    foreach (range(1, 9) as $ignored) {
        expect(allocate($subscription)->outcome)->toBe(AllocationOutcome::AlreadyAllocated);
    }

    expect($earnedSnapshot())->toBe($earnedBefore)
        // The version counter is the stronger assertion: it proves no write
        // happened at all, not merely that the value landed back where it started.
        ->and($versionSnapshot())->toBe($versionsBefore)
        ->and(LedgerEntry::count())->toBe(3);
});

it('the ledger unique index blocks a replay even if the allocation guard is bypassed', function () {
    // Simulating the worst case: something hand-crafts a second ledger write for an
    // allocation line that was already recorded. The index must stop it.
    [$subscription, $instructors] = scenario(instructors: 1);

    allocate($subscription);

    $line = AllocationLine::sole();
    $writer = app(LedgerWriter::class);

    $replayed = DB::transaction(fn () => $writer->append(
        instructorId: $line->instructor_id,
        type: LedgerEntryType::Earning,
        amount: $line->amount_minor,
        sourceType: 'allocation_line',
        sourceId: $line->id,
    ));

    // false, not an exception: a replay is a no-op, not an error.
    expect($replayed)->toBeFalse()
        ->and(LedgerEntry::count())->toBe(1)
        ->and(InstructorBalance::find($line->instructor_id)->earned_minor->minor)
        ->toBe($line->amount_minor->minor);
});

