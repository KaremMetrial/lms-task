it('uses the rate snapshotted on the subscription, not today\'s config', function () {
    $student = Student::factory()->create();

    // Sold at a 20% cut.
    $subscription = Subscription::factory()->for($student)
        ->plan(Plan::Monthly)->startingOn('2026-01-01')
        ->platformShareBps(2_000)->create();
    Payment::factory()->forSubscription($subscription)->create();

    $course = Course::factory()->create();
    Engagement::factory()->for($student)->forCourse($course)->inPeriod('2026-01')->create();

    // The platform has since raised its cut to 50%.
    config()->set('ledger.platform_share_bps', 5_000);

    $allocation = allocate($subscription)->allocation->fresh('lines');

    // Still 20%: 29_900 × 20% = 5_980 platform, 23_920 to the instructor.
    expect($allocation->platform_minor->minor)->toBe(5_980)
        ->and($allocation->instructor_pool_minor->minor)->toBe(23_920);
});

