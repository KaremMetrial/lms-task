it('gives the whole period to the platform when nobody was engaged', function () {
    $student = Student::factory()->create();
    $subscription = Subscription::factory()->for($student)
        ->plan(Plan::Monthly)->startingOn('2026-01-01')->create();
    Payment::factory()->forSubscription($subscription)->create();

    // No engagement rows at all.
    $allocation = allocate($subscription)->allocation->fresh('lines');

    expect($allocation->platform_minor->minor)->toBe(29_900)
        ->and($allocation->instructor_pool_minor->isZero())->toBeTrue()
        ->and($allocation->lines)->toHaveCount(0)
        ->and(LedgerEntry::count())->toBe(0)
        // Recorded, not skipped: the money is accounted for and the period will not
        // be reprocessed on the next run.
        ->and($allocation->balances())->toBeTrue();
});

it('counts an instructor once even across several watched courses', function () {
    $student = Student::factory()->create();
    $subscription = Subscription::factory()->for($student)
        ->plan(Plan::Monthly)->startingOn('2026-01-01')->create();
    Payment::factory()->forSubscription($subscription)->create();

    $prolific = Instructor::factory()->create();
    $other = Instructor::factory()->create();

    // Three courses by the same instructor. Without aggregation this instructor
    // would take 3/4 of the pool instead of 1/2.
    foreach (range(1, 3) as $ignored) {
        $course = Course::factory()->for($prolific)->create();
        Engagement::factory()->for($student)->forCourse($course)->inPeriod('2026-01')->create();
    }

    $course = Course::factory()->for($other)->create();
    Engagement::factory()->for($student)->forCourse($course)->inPeriod('2026-01')->create();

    $allocation = allocate($subscription)->allocation->fresh('lines');

    expect($allocation->lines)->toHaveCount(2);

    $byInstructor = $allocation->lines->keyBy('instructor_id');

    expect($byInstructor[$prolific->id]->amount_minor->minor)->toBe(10_465)
        ->and($byInstructor[$other->id]->amount_minor->minor)->toBe(10_465);
});

it('honours the watch-time strategy when it is the active one', function () {
    config()->set('ledger.allocation_strategy', WeightedByWatchTime::NAME);
    app()->forgetInstance(AllocationStrategyResolver::class);

    // 6:3:1 over a 20_930 pool.
    [$subscription] = scenario(instructors: 3, seconds: [6_000, 3_000, 1_000]);

    $allocation = allocate($subscription)->allocation->fresh('lines');

    $amounts = $allocation->lines->sortBy('instructor_id')
        ->pluck('amount_minor')->map(fn ($m) => $m->minor)->values()->all();

    expect($allocation->strategy)->toBe('watch_time')
        ->and($amounts)->toBe([12_558, 6_279, 2_093])
        ->and(array_sum($amounts))->toBe(20_930);
});

it('records a zero line without a ledger entry for an unwatched course', function () {
    config()->set('ledger.allocation_strategy', WeightedByWatchTime::NAME);
    app()->forgetInstance(AllocationStrategyResolver::class);

    [$subscription, $instructors] = scenario(instructors: 2, seconds: [3_600, 0]);

    $allocation = allocate($subscription)->allocation->fresh('lines');
    $byInstructor = $allocation->lines->keyBy('instructor_id');

    expect($allocation->lines)->toHaveCount(2)
        ->and($byInstructor[$instructors[1]->id]->amount_minor->isZero())->toBeTrue()
        // The engagement is on record; a zero-value ledger entry would be noise.
        ->and(LedgerEntry::count())->toBe(1);
});

