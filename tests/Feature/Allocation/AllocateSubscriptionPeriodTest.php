it('skips a period before the term starts', function () {
    [$subscription] = scenario(instructors: 1);

    $result = allocate($subscription, '2025-12');

    expect($result->outcome)->toBe(AllocationOutcome::Skipped)
        ->and($result->reason)->toContain('outside the recognised term')
        ->and(Allocation::count())->toBe(0);
});

it('skips a period after a cancellation', function () {
    $student = Student::factory()->create();

    $subscription = Subscription::factory()->for($student)
        ->plan(Plan::Annual)->startingOn('2026-01-01')
        ->cancelledOn('2026-04-30')->create();
    Payment::factory()->forSubscription($subscription)->create();

    $course = Course::factory()->create();
    Engagement::factory()->for($student)->forCourse($course)->inPeriod('2026-04')->create();
    Engagement::factory()->for($student)->forCourse($course)->inPeriod('2026-05')->create();

    expect(allocate($subscription, '2026-04')->outcome)->toBe(AllocationOutcome::Allocated)
        // The month after they left must recognise nothing — this is what makes a
        // pro-rata refund a no-op against instructor balances.
        ->and(allocate($subscription, '2026-05')->outcome)->toBe(AllocationOutcome::Skipped);
});

it('skips a subscription with no payment received', function () {
    $subscription = Subscription::factory()->plan(Plan::Monthly)->startingOn('2026-01-01')->create();

    $result = allocate($subscription);

    expect($result->outcome)->toBe(AllocationOutcome::Skipped)
        ->and($result->reason)->toContain('no payment');
});
